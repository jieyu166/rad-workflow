def zh_num(n: int) -> str:
    digits = "零一二三四五六七八九"
    if n < 10:
        return digits[n]
    if n == 10:
        return "十"
    if n < 20:
        return "十" + digits[n - 10]
    return "二十" + (digits[n - 20] if n > 20 else "")


def slug(title: str) -> str:
    return re.sub(r"[<>:\"/\\|?*]", "-", title).strip()


def bubbles(text: str, limit: int = 24) -> str:
    """Format readable balloon text without dropping meaning."""
    parts = [part.strip() for part in re.split(r"(?<=[，。；：？！])", text) if part.strip()]
    chunks: list[str] = []
    for part in parts:
        while len(part) > limit:
            cut = max(part.rfind(mark, 0, limit + 1) for mark in "、，；：")
            if cut < 8:
                cut = limit
            else:
                cut += 1
            chunks.append(part[:cut].strip())
            part = part[cut:].strip()
        if part:
            chunks.append(part)
    return "／".join(f"「{chunk}」" for chunk in chunks)


